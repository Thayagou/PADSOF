package vistas.herramientas;

/**
 * Clase con definiciones estáticas de tamaños
 */
public class PanelSizes {
	
	/**
	 * Constructor privado para usarlo como clase de método estáticos
	 */
	private PanelSizes() {}
	
	/** Porcentaje de altura de pantalla que ocupan los títulos */
	public static double TITLE_SIZE = 0.05;
	
	/** Porcentaje de altura de pantalla que ocupan los subtítulos */
	public static double SUBTITLE_SIZE = 0.04;

	/** Porcentaje de altura de pantalla que ocupan los títulos 3 */
	public static double TITLE3_SIZE = 0.03;

	/** Porcentaje de altura de pantalla que ocupa el texto */
	public static double TEXT_SIZE = 0.02;

	/** Porcentaje de altura de pantalla que ocupa la barra de tareas */
	public static double TOOLBAR_HEIGHT = 0.05;

	/** Porcentaje de anchura de pantalla que ocupa la barra lateral*/
	public static double OPTION_BAR_WIDTH = 0.15;

	/** Porcentaje de altura de pantalla que ocupan los botones como predeterminado */
	public static double BTN_HEIGHT = 0.05;
}
